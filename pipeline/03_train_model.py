# MAGIC ## 4. Train the three-model ensemble on (train, val)

# COMMAND ----------

with mlflow.start_run(run_name="train_pipeline") as parent_run:
    mlflow.log_params({
        "n_features":          len(FEATURES),
        "train_rows":          len(train_pd),
        "val_rows":            len(val_pd),
        "internal_test_rows":  len(test_pd),
        "train_end":           TRAIN_END_WEEK_ID,
        "val_end":             VAL_END_WEEK_ID,
        "internal_test_start": INTERNAL_TEST_START_WEEK_ID,
        "internal_test_end":   INTERNAL_TEST_END_WEEK_ID,
        "ensemble_seeds":      json.dumps(ENSEMBLE_SEEDS),
        "stacking_oof_folds":  STACKING_OOF_FOLDS,
        "calibrate_zero_clf":  CALIBRATE_ZERO_CLF,
        "dead_pair_force_zero": DEAD_PAIR_FORCE_ZERO,
    })

    # ──────────────────────── Stage 1 — zero classifier ────────────────────
    print("=" * 60)
    print("STAGE 1 — LightGBM zero classifier")
    print("=" * 60)

    clf_models = []
    clf_val_probs = []
    for seed in ENSEMBLE_SEEDS:
        print(f"  seed={seed}")
        m = train_lgb_classifier(X_tr, z_tr, X_va, z_va, seed)
        clf_models.append(m)
        clf_val_probs.append(m.predict(X_va, num_iteration=m.best_iteration))
    p_zero_val_raw = np.mean(np.stack(clf_val_probs, axis=0), axis=0)

    # Isotonic calibration (optional) — fit on val (clf, target=is_zero).
    if CALIBRATE_ZERO_CLF:
        calibrator = IsotonicRegression(out_of_bounds="clip", y_min=0.0, y_max=1.0)
        calibrator.fit(p_zero_val_raw, z_va)
        p_zero_val = calibrator.transform(p_zero_val_raw)
        print("  → isotonic calibration fitted")
    else:
        calibrator = None
        p_zero_val = p_zero_val_raw

    val_logloss = float(
        -np.mean(
            z_va * np.log(np.clip(p_zero_val, 1e-7, 1 - 1e-7))
            + (1 - z_va) * np.log(np.clip(1 - p_zero_val, 1e-7, 1 - 1e-7))
        )
    )
    mlflow.log_metric("val_logloss_clf", val_logloss)

    # ─────────────────── Stage 2a — LightGBM Tweedie regressor ─────────────
    print("=" * 60)
    print("STAGE 2a — LightGBM Tweedie regressor")
    print("=" * 60)

    lgb_reg_models = []
    lgb_reg_val_preds = []
    for seed in ENSEMBLE_SEEDS:
        print(f"  seed={seed}")
        m = train_lgb_regressor(X_tr, y_tr, X_va, y_va, seed)
        lgb_reg_models.append(m)
        lgb_reg_val_preds.append(predict_lgb(m, X_va))
    lgb_val_avg = np.mean(np.stack(lgb_reg_val_preds, axis=0), axis=0)
    mlflow.log_metric("val_wape_lgb_only", wape_numpy(y_va, lgb_val_avg))

    # ─────────────────── Stage 2b — XGBoost Tweedie regressor ──────────────
    print("=" * 60)
    print("STAGE 2b — XGBoost Tweedie regressor")
    print("=" * 60)

    xgb_reg_models = []
    xgb_reg_val_preds = []
    for seed in ENSEMBLE_SEEDS:
        print(f"  seed={seed}")
        m = train_xgb_regressor(X_tr, y_tr, X_va, y_va, seed)
        xgb_reg_models.append(m)
        xgb_reg_val_preds.append(predict_xgb(m, X_va))
    xgb_val_avg = np.mean(np.stack(xgb_reg_val_preds, axis=0), axis=0)
    mlflow.log_metric("val_wape_xgb_only", wape_numpy(y_va, xgb_val_avg))

    # ─────────────────────────── Stacker (Ridge) ───────────────────────────
    print("=" * 60)
    print("STACKER — Ridge(positive=True, fit_intercept=False)")
    print("=" * 60)

    stacker = Ridge(alpha=STACKING_RIDGE_ALPHA, positive=True, fit_intercept=False)

    if STACKING_OOF_FOLDS >= 2:
        # TimeSeriesSplit on train sorted by week_id. Only the first seed is
        # used for OOF (adding more seeds here is redundant with averaging).
        print(f"  Fitting OOF stacker with {STACKING_OOF_FOLDS} folds (first seed only)...")
        order = np.argsort(train_pd["week_id"].values, kind="stable")
        inv_order = np.empty_like(order)
        inv_order[order] = np.arange(len(order))

        X_tr_sorted = X_tr.iloc[order].reset_index(drop=True)
        y_tr_sorted = y_tr[order]

        oof_lgb_s = np.full(len(X_tr_sorted), np.nan, dtype=float)
        oof_xgb_s = np.full(len(X_tr_sorted), np.nan, dtype=float)

        tscv = TimeSeriesSplit(n_splits=STACKING_OOF_FOLDS)
        first_seed = ENSEMBLE_SEEDS[0]
        for fold_ix, (tr_idx, va_idx) in enumerate(tscv.split(X_tr_sorted)):
            print(f"   fold {fold_ix + 1}/{STACKING_OOF_FOLDS}")
            Xf_tr = X_tr_sorted.iloc[tr_idx]
            yf_tr = y_tr_sorted[tr_idx]
            Xf_va = X_tr_sorted.iloc[va_idx]
            yf_va = y_tr_sorted[va_idx]

            m_lgb_f = train_lgb_regressor(Xf_tr, yf_tr, Xf_va, yf_va, first_seed)
            oof_lgb_s[va_idx] = predict_lgb(m_lgb_f, Xf_va)
            del m_lgb_f; gc.collect()

            m_xgb_f = train_xgb_regressor(Xf_tr, yf_tr, Xf_va, yf_va, first_seed)
            oof_xgb_s[va_idx] = predict_xgb(m_xgb_f, Xf_va)
            del m_xgb_f; gc.collect()

        # Invert the sort so the OOF arrays match the original train order.
        oof_lgb = oof_lgb_s[inv_order]
        oof_xgb = oof_xgb_s[inv_order]
        oof_mask = ~np.isnan(oof_lgb)

        bl_tr = baseline_matrix(train_pd)
        stack_fit_X = np.column_stack([
            oof_lgb[oof_mask],
            oof_xgb[oof_mask],
            bl_tr[oof_mask],
        ])
        stack_fit_y = y_tr[oof_mask]
        stacker.fit(stack_fit_X, stack_fit_y)
        stack_fit_source = f"oof_train (n={oof_mask.sum()}/{len(y_tr)})"
    else:
        print("  Fitting Ridge on validation predictions (STACKING_OOF_FOLDS < 2)")
        bl_va_fit = baseline_matrix(val_pd)
        stack_fit_X = np.column_stack([lgb_val_avg, xgb_val_avg, bl_va_fit])
        stacker.fit(stack_fit_X, y_va)
        stack_fit_source = "val_predictions"

    coef = stacker.coef_
    stack_feature_names = ["lgb", "xgb"] + STACK_BASELINE_COLS
    print("  Ridge weights:")
    for name, w in zip(stack_feature_names, coef):
        print(f"    {name:<12s} = {w: .4f}")
    mlflow.log_params({f"ridge_w_{n}": float(w) for n, w in zip(stack_feature_names, coef)})
    mlflow.log_param("stack_fit_source", stack_fit_source)

    # ─────────────── Apply the stacker on val, then adaptive threshold ─────
    bl_va = baseline_matrix(val_pd)
    stack_va = np.column_stack([lgb_val_avg, xgb_val_avg, bl_va])
    blend_val_raw = np.clip(stacker.predict(stack_va), 0.0, None)

    # Adaptive (base, slope) grid sweep on the calibrated zero proba.
    zero_rate_val = np.nan_to_num(val_pd[ZERO_RATE_FEATURE].values.astype(float), nan=0.0)
    is_dead_val = val_pd["is_dead_pair"].values.astype(int)

    best_base, best_slope, best_wape = None, None, float("inf")
    sweep_rows = []
    for base in ADAPTIVE_THRESHOLD_BASE_GRID:
        for slope in ADAPTIVE_THRESHOLD_SLOPE_GRID:
            thr = np.clip(
                base - slope * zero_rate_val,
                ADAPTIVE_THRESHOLD_CLIP[0],
                ADAPTIVE_THRESHOLD_CLIP[1],
            )
            is_zero_pred = p_zero_val > thr
            final_val = np.where(is_zero_pred, 0.0, blend_val_raw)
            if DEAD_PAIR_FORCE_ZERO:
                final_val = np.where(is_dead_val == 1, 0.0, final_val)
            w = wape_numpy(y_va, final_val)
            sweep_rows.append({"base": base, "slope": slope, "wape": w})
            if w < best_wape:
                best_base, best_slope, best_wape = base, slope, w

    sweep_df = pd.DataFrame(sweep_rows).sort_values("wape")
    print(sweep_df.head(8).to_string(index=False))
    print(f"  → best base={best_base}, slope={best_slope}, WAPE={best_wape:.4f}")

    mlflow.log_params({
        "adaptive_base":  float(best_base),
        "adaptive_slope": float(best_slope),
    })
    mlflow.log_metric("val_wape_model", float(best_wape))
    sweep_df.to_csv("/tmp/threshold_sweep.csv", index=False)
    mlflow.log_artifact("/tmp/threshold_sweep.csv")

    # Final val prediction column with the chosen (base, slope).
    effective_thr_val = np.clip(
        best_base - best_slope * zero_rate_val,
        ADAPTIVE_THRESHOLD_CLIP[0],
        ADAPTIVE_THRESHOLD_CLIP[1],
    )
    val_final = np.where(p_zero_val > effective_thr_val, 0.0, blend_val_raw)
    if DEAD_PAIR_FORCE_ZERO:
        val_final = np.where(is_dead_val == 1, 0.0, val_final)

    # ───────── Score the labelled internal test set (same pipeline, once) ──
    clf_probs_te = np.mean(
        np.stack([m.predict(X_te, num_iteration=m.best_iteration) for m in clf_models], axis=0),
        axis=0,
    )
    p_zero_te = calibrator.transform(clf_probs_te) if calibrator is not None else clf_probs_te

    lgb_te_avg = np.mean(np.stack([predict_lgb(m, X_te) for m in lgb_reg_models], axis=0), axis=0)
    xgb_te_avg = np.mean(np.stack([predict_xgb(m, X_te) for m in xgb_reg_models], axis=0), axis=0)

    bl_te = baseline_matrix(test_pd)
    blend_te_raw = np.clip(
        stacker.predict(np.column_stack([lgb_te_avg, xgb_te_avg, bl_te])),
        0.0, None,
    )

    zero_rate_te = np.nan_to_num(test_pd[ZERO_RATE_FEATURE].values.astype(float), nan=0.0)
    is_dead_te = test_pd["is_dead_pair"].values.astype(int)
    thr_te = np.clip(
        best_base - best_slope * zero_rate_te,
        ADAPTIVE_THRESHOLD_CLIP[0],
        ADAPTIVE_THRESHOLD_CLIP[1],
    )
    test_final = np.where(p_zero_te > thr_te, 0.0, blend_te_raw)
    if DEAD_PAIR_FORCE_ZERO:
        test_final = np.where(is_dead_te == 1, 0.0, test_final)

    internal_test_wape = wape_numpy(y_te, test_final)
    mlflow.log_metric("internal_test_wape", float(internal_test_wape))
    print(f"  internal test WAPE = {internal_test_wape:.4f}")

    # COMMAND ----------

    # MAGIC %md
    # MAGIC ## 5. Persist models + stacker + calibrator as MLflow artifacts

    # COMMAND ----------

    tmpdir = tempfile.mkdtemp(prefix="ensemble_")
    # LGB boosters → text format (portable, fast to reload via lgb.Booster).
    for seed, m in zip(ENSEMBLE_SEEDS, clf_models):
        m.save_model(os.path.join(tmpdir, f"clf_lgb_seed{seed}.txt"))
    for seed, m in zip(ENSEMBLE_SEEDS, lgb_reg_models):
        m.save_model(os.path.join(tmpdir, f"reg_lgb_seed{seed}.txt"))
    # XGB boosters → UBJ (binary, compact).
    for seed, m in zip(ENSEMBLE_SEEDS, xgb_reg_models):
        m.save_model(os.path.join(tmpdir, f"reg_xgb_seed{seed}.ubj"))

    with open(os.path.join(tmpdir, "stacker.pkl"), "wb") as f:
        pickle.dump(stacker, f)
    if calibrator is not None:
        with open(os.path.join(tmpdir, "calibrator.pkl"), "wb") as f:
            pickle.dump(calibrator, f)

    manifest = {
        "ensemble_seeds":        ENSEMBLE_SEEDS,
        "clf_best_iter":         [int(m.best_iteration) for m in clf_models],
        "lgb_reg_best_iter":     [int(m.best_iteration) for m in lgb_reg_models],
        "xgb_reg_best_iter":     [int(m.best_iteration) for m in xgb_reg_models],
        "calibrate_zero_clf":    CALIBRATE_ZERO_CLF,
        "stacker_features":      stack_feature_names,
        "stacker_coef":          coef.tolist(),
        "stack_baseline_cols":   STACK_BASELINE_COLS,
        "adaptive_base":         float(best_base),
        "adaptive_slope":        float(best_slope),
        "adaptive_clip":         list(ADAPTIVE_THRESHOLD_CLIP),
        "zero_rate_feature":     ZERO_RATE_FEATURE,
        "dead_pair_force_zero":  DEAD_PAIR_FORCE_ZERO,
        "features":              FEATURES,
        "features_categorical":  FEATURES_CATEGORICAL,
        "val_wape":              float(best_wape),
        "internal_test_wape":    float(internal_test_wape),
    }
    with open(os.path.join(tmpdir, "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)

    mlflow.log_artifacts(tmpdir, artifact_path=MLFLOW_ENSEMBLE_ARTIFACT_PATH)
    print(f"  Ensemble artifacts logged under '{MLFLOW_ENSEMBLE_ARTIFACT_PATH}/'")

    # COMMAND ----------

    # MAGIC %md
    # MAGIC ## 6. Write validation + internal test predictions to Delta

    # COMMAND ----------

    # Schema extended with `threshold` so 04_evaluate / 05_inference can
    # reproduce the decision rule row by row, without looking up params.
    schema = StructType([
        StructField("semaine",      StringType()),
        StructField("code_agence",  LongType()),
        StructField("code_article", LongType()),
        StructField("quantite",     LongType()),
        StructField("p_zero",       DoubleType()),
        StructField("qty_pred",     DoubleType()),
        StructField("prediction",   DoubleType()),
        StructField("threshold",    DoubleType()),
    ])

    val_out = val_pd[["semaine", "code_agence", "code_article", "quantite"]].copy()
    val_out["p_zero"]     = p_zero_val
    val_out["qty_pred"]   = blend_val_raw
    val_out["prediction"] = val_final
    val_out["threshold"]  = effective_thr_val
    (
        spark.createDataFrame(val_out, schema=schema).write
        .format("delta").mode("overwrite").option("overwriteSchema", "true")
        .saveAsTable(TBL_VAL_PREDICTIONS)
    )
    print(f"  Wrote validation predictions to {TBL_VAL_PREDICTIONS}")

    test_out = test_pd[["semaine", "code_agence", "code_article", "quantite"]].copy()
    test_out["p_zero"]     = p_zero_te
