def train_lgb_classifier(X_tr_, z_tr_, X_va_, z_va_, seed: int):
    params = dict(LGB_PARAMS_ZERO)
    params["seed"] = seed
    dtr = lgb.Dataset(
        X_tr_, label=z_tr_,
        categorical_feature=FEATURES_CATEGORICAL,
        free_raw_data=False,
    )
    dva = lgb.Dataset(
        X_va_, label=z_va_,
        reference=dtr,
        categorical_feature=FEATURES_CATEGORICAL,
        free_raw_data=False,
    )
    return lgb.train(
        params, dtr,
        num_boost_round=LGB_NUM_ROUNDS_ZERO,
        valid_sets=[dva], valid_names=["val"],
        callbacks=[
            lgb.early_stopping(LGB_EARLY_STOP_ZERO, first_metric_only=True),
            lgb.log_evaluation(period=200),
        ],
    )


def train_lgb_regressor(X_tr_, y_tr_, X_va_, y_va_, seed: int):
    # NOTE: no sample_weight. Tweedie already has an implicit heteroskedastic
    # weighting (variance ∝ μ^p), so multiplying the loss by y double-counts
    # high-volume rows and pushes the fit to over-predict. Stick to plain
    # Tweedie — this matches the Fourth-good-model notebook.
    params = dict(LGB_PARAMS_QTY)
    params["seed"] = seed
    params["metric"] = "None"  # feval below is authoritative
    dtr = lgb.Dataset(
        X_tr_, label=y_tr_,
        categorical_feature=FEATURES_CATEGORICAL,
        free_raw_data=False,
    )
    dva = lgb.Dataset(
        X_va_, label=y_va_,
        reference=dtr,
        categorical_feature=FEATURES_CATEGORICAL,
        free_raw_data=False,
    )
    return lgb.train(
        params, dtr,
        num_boost_round=LGB_NUM_ROUNDS_QTY,
        valid_sets=[dva], valid_names=["val"],
        feval=wape_lgb_feval,
        callbacks=[
            lgb.early_stopping(LGB_EARLY_STOP_QTY, first_metric_only=True),
            lgb.log_evaluation(period=200),
        ],
    )


def train_xgb_regressor(X_tr_, y_tr_, X_va_, y_va_, seed: int):
    # Same rationale as train_lgb_regressor: no sample_weight on Tweedie.
    params = dict(XGB_PARAMS_QTY)
    params["seed"] = seed
    dtr = xgb.DMatrix(X_tr_, label=y_tr_, enable_categorical=True)
    dva = xgb.DMatrix(X_va_, label=y_va_, enable_categorical=True)
    return xgb.train(
        params, dtr,
        num_boost_round=XGB_NUM_ROUNDS_QTY,
        evals=[(dva, "val")],
        early_stopping_rounds=XGB_EARLY_STOP_QTY,
        verbose_eval=200,
    )


def predict_lgb(m, X) -> np.ndarray:
    return np.clip(m.predict(X, num_iteration=m.best_iteration), 0.0, None)


def predict_xgb(m, X) -> np.ndarray:
    dm = xgb.DMatrix(X, enable_categorical=True)
    return np.clip(m.predict(dm, iteration_range=(0, m.best_iteration + 1)), 0.0, None)


def baseline_matrix(df: pd.DataFrame) -> np.ndarray:
    """(N, k) matrix of baseline columns used by the Ridge stacker.

    `lag_52`, `pair_mean`, `pair_median` are already materialised in the
    gold feature table, so we don't recompute them — we just stack and
    zero-fill NaNs so Ridge stays happy.
    """
    cols = [np.nan_to_num(df[c].values.astype(float), nan=0.0) for c in STACK_BASELINE_COLS]
    return np.column_stack(cols)

