# Databricks notebook source
# MAGIC %md
# MAGIC # 03 — Train the ensemble model
# MAGIC
# MAGIC **Architecture (Fourth-good-model port):**
# MAGIC - **Stage 1** — binary LightGBM classifier predicts `P(quantite = 0)`.
# MAGIC   Optionally isotonic-calibrated on validation so the output probability
# MAGIC   is monotone in the true zero rate.
# MAGIC - **Stage 2a** — LightGBM Tweedie regressor on raw `quantite`, trained
# MAGIC   on every row (including zeros) with sample weights proportional to
# MAGIC   the magnitude (WAPE-aligned).
# MAGIC - **Stage 2b** — XGBoost Tweedie regressor with the same setup. Only
# MAGIC   purpose: ensemble diversity — LGB and XGB have different split
# MAGIC   strategies and categorical handling, so their errors decorrelate.
# MAGIC - **Stacker** — `sklearn.linear_model.Ridge(positive=True,
# MAGIC   fit_intercept=False)` blends five signals: `lgb_pred`, `xgb_pred`,
# MAGIC   `lag_52`, `pair_mean`, `pair_median`. Fitted on **out-of-fold**
# MAGIC   predictions generated by `TimeSeriesSplit` on the training set so the
# MAGIC   stacker cannot overfit validation. Falls back to a val-fit if
# MAGIC   `STACKING_OOF_FOLDS < 2`.
# MAGIC - **Adaptive threshold** — `thr = clip(base - slope * zero_rate, lo, hi)`,
# MAGIC   swept on a small (base, slope) grid against val WAPE.
# MAGIC - **Hard dead-pair override** — `is_dead_pair == 1 → 0`.
# MAGIC - **Multi-seed** — each stage can train k models (config-driven) and
# MAGIC   averages predictions before stacking.
# MAGIC
# MAGIC **No hyperparameter tuning is performed.** Every knob comes from
# MAGIC `00_config.py` and is either fixed or selected by a tiny grid sweep.
# MAGIC
# MAGIC **Inputs:** `gold_train`, `gold_validation`, `gold_internal_test`.
# MAGIC **Outputs:**
# MAGIC - All models, the stacker, the calibrator, and a `manifest.json` written
# MAGIC   under the MLflow artifact path `MLFLOW_ENSEMBLE_ARTIFACT_PATH`.
# MAGIC - Validation + internal-test predictions as Delta tables, including a
# MAGIC   per-row `threshold` column so downstream notebooks can reproduce the
# MAGIC   decision rule without looking up parameters in MLflow.

